// The Ansible inventory `forge install` generates for a host, in the shape of
// ansible/inventory.lima.example.yml and ansible/inventory.example.yml, and
// the one of a cloud host's relay.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { ForgeError } from "../context.ts";
import { shellQuote } from "../shell.ts";
import type { CloudSettings } from "./cloud.ts";
import { sshOption } from "./ssh-config.ts";
import type { LaptopHost } from "./state.ts";

// Same alias as the Lima wait (lima.ts), which stores the VM's key under it.
const HOST_KEY_ALIAS = "forge-local-admin";

// Every string is a YAML double-quoted scalar, every list a flow sequence:
// JSON is valid YAML.
const q = (v: string | string[]): string => JSON.stringify(v);

// Two splits: Ansible splits ansible_ssh_common_args with shlex, then ssh
// splits each -o value again, like a config line. A path or a socket is
// quoted for ssh (sshOption), then the whole option for shlex.
function sshCommonArgs(h: LaptopHost, knownHosts: string): string {
  const path = (name: string, v: string): string => `-o ${shellQuote(sshOption(name, v))}`;
  const args = ["-o IdentitiesOnly=yes", path("UserKnownHostsFile", knownHosts)];
  if (h.kind === "lima") args.push(`-o HostKeyAlias=${HOST_KEY_ALIAS}`, "-o StrictHostKeyChecking=accept-new");
  // Ansible connects by address, not by the alias whose ForwardAgent no would
  // apply: a Host * of ~/.ssh/config must not forward the agent to the dev VM
  // (a -o on the command line wins over the config files).
  if (h.kind === "cloud") args.push("-o ForwardAgent=no");
  if (h.identityAgent) args.push(path("IdentityAgent", h.identityAgent));
  return args.join(" ");
}

export function renderInventory(
  h: LaptopHost,
  o: { forgeKey: string; adminKeyFile: string; knownHosts: string;
    contributor?: { upstream: string; fork: string; gitName: string; gitEmail: string };
  },
): string {
  // No ansible_port for a remote host: an explicit one would stop the preflight
  // from probing forge_ssh_port, locking out a developer who edits it. Lima
  // forwards a local port to sshd, which stays on 22: it needs ansible_port.
  const port = h.kind === "lima" ? [`      ansible_port: ${h.port}`] : [];
  return [
    "---",
    "# Generated by `forge install`. It is written once: your edits are kept on",
    "# re-runs. ssh_keys is authoritative: keys added by hand to the user's",
    "# authorized_keys are removed on the next run.",
    "all:",
    "  hosts:",
    `    ${h.name}:`,
    `      ansible_host: ${q(h.address)}`,
    ...port,
    `      ansible_user: ${q(h.admin)}`,
    `      ansible_ssh_private_key_file: ${q(o.adminKeyFile)}`,
    `      ansible_ssh_common_args: ${q(sshCommonArgs(h, o.knownHosts))}`,
    "  vars:",
    `    forge_exposure: ${q(h.exposure)}`,
    ...(o.contributor
      ? [
        `    forge_contributor_upstream: ${q(o.contributor.upstream)}`,
        `    forge_contributor_fork: ${q(o.contributor.fork)}`,
        `    forge_contributor_git_name: ${q(o.contributor.gitName)}`,
        `    forge_contributor_git_email: ${q(o.contributor.gitEmail)}`,
      ]
      : []),
    // site.yml sets the forge user's groups exactly; vm-test.sh --lima on the
    // dev VM runs QEMU with KVM as that user.
    ...(h.kind === "cloud" ? ['    forge_users_extra_groups: ["kvm"]'] : []),
    "    forge_users:",
    `      - name: ${q(h.user)}`,
    "        ssh_keys:",
    `          - ${q(o.forgeKey)}`,
    "",
  ].join("\n");
}

// A cloud host's relay, for ansible/relay.yml: the same admin, key and SSH
// arguments as its dev VM (OpenTofu gives both instances the same
// cloud-init), and the relay's inputs (roles/forge_relay/defaults/main.yml).
// The bot works on its fork: the fork's owner is the bot's login.
export function renderRelayInventory(
  h: LaptopHost, s: CloudSettings, o: { adminKeyFile: string; knownHosts: string; subnetCidr: string },
): string {
  if (!h.relayAddress) throw new ForgeError(`${h.name} has no relay address yet: run forge cloud create --host ${h.name}`);
  if (!s.trustedLogins) throw new ForgeError(`${h.name}'s cloud settings name no trusted logins: run forge cloud create --host ${h.name}`);
  return [
    "---",
    "# Generated by `forge cloud create`. It is written once: your edits are kept",
    "# on re-runs.",
    "all:",
    "  hosts:",
    `    ${h.name}-relay:`,
    `      ansible_host: ${q(h.relayAddress)}`,
    `      ansible_user: ${q(h.admin)}`,
    `      ansible_ssh_private_key_file: ${q(o.adminKeyFile)}`,
    `      ansible_ssh_common_args: ${q(sshCommonArgs(h, o.knownHosts))}`,
    "  vars:",
    `    forge_exposure: ${q(h.exposure)}`,
    `    forge_relay_upstream: ${q(s.upstream)}`,
    `    forge_relay_fork: ${q(s.fork)}`,
    `    forge_relay_bot_login: ${q(s.fork.split("/")[0])}`,
    `    forge_relay_bot_name: ${q(s.botName)}`,
    `    forge_relay_bot_email: ${q(s.botEmail)}`,
    `    forge_relay_trusted_logins: ${q(s.trustedLogins)}`,
    // None recorded: the role's default.
    ...(s.coAuthorEmails ? [`    forge_relay_co_author_emails: ${q(s.coAuthorEmails)}`] : []),
    `    forge_relay_client_cidr: ${q(o.subnetCidr)}`,
    "",
  ].join("\n");
}

// An existing inventory is never overwritten.
export function writeInventoryOnce(path: string, text: string): "written" | "kept" {
  if (existsSync(path)) return "kept";
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  writeFileSync(path, text, { mode: 0o600, flag: "wx" });
  return "written";
}

import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { renderInventory, writeInventoryOnce } from "../cli/lib/laptop/inventory.ts";
import type { LaptopHost } from "../cli/lib/laptop/state.ts";

const lima: LaptopHost = {
  name: "forge-local", kind: "lima", address: "127.0.0.1", port: 60022, user: "forge",
  admin: "alice", adminKey: "/lima/_config/user", exposure: "local", done: [],
};
const remote: LaptopHost = {
  name: "forge-acme", kind: "remote", address: "203.0.113.10", port: 22, user: "forge",
  admin: "ubuntu", adminKey: "/keys/admin", exposure: "public", done: [],
};
const KEY = "ssh-ed25519 AAAAC3 alice's \"work\": laptop";

function opts(extra: Partial<{ knownHosts: string }> = {}) {
  return { forgeKey: KEY, adminKeyFile: "/keys/admin", knownHosts: "/state/known_hosts", ...extra };
}

const hasAnsible = spawnSync("ansible-inventory", ["--version"]).status === 0;

const hasSsh = spawnSync("ssh", ["-V"]).status === 0;

// Split like Ansible does (shlex, POSIX): a backslash outside quotes escapes
// the next character.
function shlex(s: string): string[] {
  const out: string[] = [];
  let cur = "", inWord = false, q = "", esc = false;
  for (const c of s) {
    if (esc) { cur += c; esc = false; }
    else if (q) { if (c === q) q = ""; else cur += c; }
    else if (c === "\\") { esc = true; inWord = true; }
    else if (c === "'" || c === '"') { q = c; inWord = true; }
    else if (c === " ") { if (inWord || cur) out.push(cur); cur = ""; inWord = false; }
    else { cur += c; inWord = true; }
  }
  if (inWord || cur) out.push(cur);
  return out;
}

// What Ansible hands to ssh: the inventory's ansible_ssh_common_args, split.
const commonArgs = (inventory: string): string[] =>
  shlex(JSON.parse(/^ {6}ansible_ssh_common_args: (.*)$/m.exec(inventory)![1]));

test("lima inventory parses back with the expected values", { skip: !hasAnsible }, () => {
  const dir = mkdtempSync(join(tmpdir(), "inv-"));
  const file = join(dir, "inventory.yml");
  writeFileSync(file, renderInventory({ ...lima, identityAgent: "/run/my agent.sock" },
    opts({ knownHosts: "/state dir/known_hosts" })));
  const r = spawnSync("ansible-inventory", ["-i", file, "--list"], { encoding: "utf8" });
  assert.equal(r.status, 0, r.stderr);
  const j = JSON.parse(r.stdout);
  const h = j._meta.hostvars["forge-local"];
  assert.equal(h.ansible_host, "127.0.0.1");
  assert.equal(h.ansible_port, 60022);
  assert.equal(h.ansible_user, "alice");
  assert.equal(h.ansible_ssh_private_key_file, "/keys/admin");
  assert.equal(h.forge_exposure, "local");
  assert.deepEqual(h.forge_users, [{ name: "forge", ssh_keys: [KEY] }]);
  assert.deepEqual(shlex(h.ansible_ssh_common_args), [
    "-o", "IdentitiesOnly=yes", "-o", 'UserKnownHostsFile="/state dir/known_hosts"',
    "-o", "HostKeyAlias=forge-local-admin", "-o", "StrictHostKeyChecking=accept-new",
    "-o", 'IdentityAgent="/run/my agent.sock"',
  ]);
});

test("remote inventory has no HostKeyAlias, accept-new or ansible_port", { skip: !hasAnsible }, () => {
  const dir = mkdtempSync(join(tmpdir(), "inv-"));
  const file = join(dir, "inventory.yml");
  writeFileSync(file, renderInventory(remote, opts()));
  const r = spawnSync("ansible-inventory", ["-i", file, "--list"], { encoding: "utf8" });
  assert.equal(r.status, 0, r.stderr);
  const h = JSON.parse(r.stdout)._meta.hostvars["forge-acme"];
  assert.equal(h.ansible_host, "203.0.113.10");
  assert.equal(h.ansible_user, "ubuntu");
  assert.equal(h.forge_exposure, "public");
  assert.equal("ansible_port" in h, false);
  assert.doesNotMatch(h.ansible_ssh_common_args, /HostKeyAlias|accept-new/);
});

test("remote rendering text", () => {
  const t = renderInventory(remote, opts());
  assert.doesNotMatch(t, /HostKeyAlias|accept-new|ansible_port/);
  assert.match(t, /Generated by `forge install`/);
  assert.match(t, /-o IdentitiesOnly=yes -o 'UserKnownHostsFile=\/state\/known_hosts'/);
});

test("lima rendering keeps ansible_port and the exact quoted args", () => {
  const t = renderInventory({ ...lima, identityAgent: "/a b/s" }, opts({ knownHosts: "/x y/kh" }));
  assert.match(t, /ansible_port: 60022/);
  // The YAML scalar is JSON: ssh's double quotes are escaped in the file.
  assert.ok(t.includes(String.raw`-o IdentitiesOnly=yes -o 'UserKnownHostsFile=\"/x y/kh\"' -o HostKeyAlias=forge-local-admin -o StrictHostKeyChecking=accept-new -o 'IdentityAgent=\"/a b/s\"'`), t);
});

// ssh reads a -o value like a config line and splits it on whitespace again:
// the paths must reach it in its own quotes. `-G` only parses, never connects.
// Two spaces in a row tell a whole path from one split and joined back.
test("ssh itself reads the split args back with whole paths", { skip: !hasSsh }, () => {
  const agent = "/Users/o'brien/Library/Group  Containers/agent.sock";
  const knownHosts = "/state  dir/known_hosts";
  const args = commonArgs(renderInventory({ ...lima, identityAgent: agent }, opts({ knownHosts })));
  const r = spawnSync("ssh", ["-F", "/dev/null", "-G", ...args, "example.invalid"], { encoding: "utf8" });
  assert.equal(r.status, 0, r.stderr);
  const value = (key: string) => r.stdout.split("\n").find((l) => l.startsWith(`${key} `))?.slice(key.length + 1);
  assert.equal(value("identityagent"), agent);
  assert.equal(value("userknownhostsfile"), knownHosts);
  assert.equal(value("hostkeyalias"), "forge-local-admin");
});

test("a key comment with quotes and a colon survives", () => {
  const t = renderInventory(remote, opts());
  assert.ok(t.includes(JSON.stringify(KEY)));
});

test("writeInventoryOnce keeps an existing file", () => {
  const file = join(mkdtempSync(join(tmpdir(), "inv-")), "inventory.yml");
  assert.equal(writeInventoryOnce(file, "one"), "written");
  assert.equal(writeInventoryOnce(file, "two"), "kept");
  assert.equal(readFileSync(file, "utf8"), "one");
});

test("a cloud inventory carries the contributor variables as quoted scalars", () => {
  const cloud: LaptopHost = { ...remote, name: "forge-dev", kind: "cloud" };
  const t = renderInventory(cloud, {
    ...opts(),
    contributor: { upstream: "acme/forge", fork: "bot/forge", gitName: 'Bot "One"', gitEmail: "bot@example.org" },
  });
  assert.match(t, /^ {4}forge_contributor_upstream: "acme\/forge"$/m);
  assert.match(t, /^ {4}forge_contributor_fork: "bot\/forge"$/m);
  assert.match(t, /^ {4}forge_contributor_git_name: "Bot \\"One\\""$/m);
  assert.match(t, /^ {4}forge_contributor_git_email: "bot@example.org"$/m);
  assert.match(t, /forge_exposure: "public"/);
  assert.doesNotMatch(t, /ansible_port|HostKeyAlias/);
});

// The playbook connects by address, not by the alias: the alias's
// ForwardAgent no would not apply, and a `Host *` of the developer's could
// forward the agent to the dev VM. A -o on the command line wins over it.
test("a cloud inventory turns agent forwarding off, whatever ~/.ssh/config says", { skip: !hasSsh }, () => {
  const cloud: LaptopHost = { ...remote, name: "forge-dev", kind: "cloud" };
  const args = commonArgs(renderInventory(cloud, opts()));
  assert.ok(args.join(" ").includes("-o ForwardAgent=no"), args.join(" "));
  const config = join(mkdtempSync(join(tmpdir(), "inv-")), "config");
  writeFileSync(config, "Host *\n  ForwardAgent yes\n");
  const r = spawnSync("ssh", ["-F", config, "-G", ...args, "203.0.113.20"], { encoding: "utf8" });
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /^forwardagent no$/m);
});
